import numpy as np

# 1d array with only specific value
# np.full(how many element, value what we put) - it store whole array with any specific value
arr = np.full(5, 9)

print(arr)

# 2d / matrix array
# np.full((how many rows, how many columns), value what we put) - it store whole array with any specific value
arr2 = np.full((3, 3), 8)

print(arr2)